def short_name(npc_name: str) -> str:
    """npc_dota_hero_ursa → ursa."""
    return npc_name.removeprefix(NPC_PREFIX)


def ru_title(short: str) -> str:
    names = ALIASES.get(short)
    return names[0].capitalize() if names else ""
