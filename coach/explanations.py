def stats_summary(item_data, limit=3):
    parts = []
    for a in (item_data or {}).get("attrib") or []:
        if not isinstance(a, dict):
            continue
        ru = ATTR_RU.get(a.get("key"))
        val = a.get("value")
        if not ru or val in (None, "", "0"):
            continue
        if isinstance(val, list):
            val = val[0]
        val = str(val).split(" ")[0]
        sep = "" if ru.startswith("%") else " "
        parts.append(f"+{val}{sep}{ru}")
        if len(parts) >= limit:
            break
    return ", ".join(parts)


def essence(item, item_db):
    """Кратко: что даёт предмет. Ручной текст (если есть) + кнопка + основные статы."""
    data = item_db.items.get(item) or {}
    text = WHY.get(item, "")
    active = [a.get("title") for a in data.get("abilities") or []
              if isinstance(a, dict) and a.get("type") == "active" and a.get("title")]
    if active and not text:
        text = f"Активная способность: {active[0]}."
    stats = stats_summary(data, limit=3)
    if stats:
        text = (text + " " if text else "") + f"Статы: {stats}."
    return text or "Популярный предмет на этом герое."


def explain(item, item_db, stage, hero_title="", partial=False):
    text = WHY.get(item)
    if not text:
        text = GENERIC_BY_STAGE.get(stage, "")
        stats = stats_summary(item_db.items.get(item))
        if stats:
            text += f" Даёт: {stats}."
    if partial:
        text += " Часть компонентов уже есть — закончите сборку, прежде чем начинать новую."
    return text.strip()
